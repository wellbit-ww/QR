/**
 * Живые формулировки SDB151NM: что отвечает каталог vs чего ждём по РЭ.
 * node scripts/probe-sdb151nm-live.js
 */
const { tryDeterministicSdb151nmAnswer } = require("../src/rag/sdb151nm-direct-facts");
const { classifySdb151nmMessage } = require("../src/rag/sdb151nm-chat-gate");

const cases = [
  ["Колёса в комплекте?", /не входят/i],
  ["Входят ли транспортные колёса в базовую поставку?", /не входят/i],
  ["Сколько кг весит шкаф?", /46/],
  ["Какие размеры у этого шкафа?", /602/],
  ["Сколько осушителей в комплекте?", /1 осушител/i],
  ["Есть ли регулируемые ножки?", /ножк/i],
  ["Какой длины шнур питания?", /4\s*м/],
  ["Есть ли подогрев у 151?", /1\.4|не указан|не привед/i],
  ["До скольки подогрев?", /1\.4|не привед/i],
  ["Какая максимальная температура подогрева?", /1\.4|не указан|не привед/i],
  ["Что на дисплее горит в обычной работе?", /влажност/i],
  ["Какой объём в литрах?", /не указан/i],
  ["Сколько дверей?", /не указан|не подтвержд/i],
  ["Из чего корпус?", /стал/i],
  ["Сломалась дверь, как починить?", /двери/i],
  ["Можно ли самому поменять стекло?", /нет инструкции|техподдерж/i],
  ["Куда звонить если сломался?", /8 \(800\) 200-54-17/],
  ["Как часто менять осушитель?", /36 месяцев/],
  ["Влажность пищит и не падает, что делать?", /3\.1\.4/],
];

let fail = 0;
for (const [q, re] of cases) {
  const gate = classifySdb151nmMessage(q, { equipmentChatScoped: true });
  const ans = tryDeterministicSdb151nmAnswer(q) || "";
  const ok = re.test(ans);
  if (!ok) fail += 1;
  console.log(ok ? "PASS" : "FAIL", q);
  console.log("  gate:", gate.action, "match:", ok);
  console.log("  ", ans.replace(/\s+/g, " ").slice(0, 180));
}
process.exit(fail ? 1 : 0);
