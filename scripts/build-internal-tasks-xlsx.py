def main() -> None:
    wb = Workbook()
    ws = wb.active
    ws.title = "Внутренние проекты"

    headers = ["№", "Проект", "Папка", "Компонент", "Задача", "Статус"]
    ws.append(headers)

    header_fill = PatternFill("solid", fgColor="1565C0")
    header_font = Font(bold=True, color="FFFFFF")
    for col in range(1, len(headers) + 1):
        cell = ws.cell(row=1, column=col)
        cell.fill = header_fill
        cell.font = header_font
        cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)

    for i, (project, folder, component, task, status) in enumerate(ROWS, start=1):
        ws.append([i, project, folder, component, task, status])

    widths = [6, 34, 18, 18, 88, 14]
    for idx, width in enumerate(widths, start=1):
        ws.column_dimensions[get_column_letter(idx)].width = width

    for row in ws.iter_rows(min_row=2, max_row=ws.max_row):
        for cell in row:
            cell.alignment = Alignment(vertical="top", wrap_text=True)

    ws.freeze_panes = "A2"
    ws.auto_filter.ref = f"A1:F{ws.max_row}"

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    wb.save(OUTPUT)
    print(OUTPUT)
    print(f"rows={len(ROWS)}")


if __name__ == "__main__":
    main()
