function buildSdb702nmLlmAnswerCompositionBlocks(retrievalContext, userMessage = "") {
  const blocks = [];
  const ctx = String(retrievalContext || "");
  const msg = String(userMessage || "");

  if (
    ctx.length > 400 &&
    /(?:опиш|что\s+произойд|что\s+входит|как\s+работ|запрещ|погрузочн|ротаметр|конвекц|как\s+включ|как\s+открыт)/i.test(
      msg,
    )
  ) {
    blocks.push(
      "",
      "Процедурный / описательный вопрос (SDB702NM):",
      "Ответ только по шагам и формулировкам из контекста РЭ.",
      "ЗАПРЕЩЕНО выдумывать «тестовый режим», отдельную процедуру открытия дверей и шаги меню, которых нет в контексте.",
      `Если частичного ответа нет — «${STRICT_ABSTAIN}», а не догадки.`,
    );
  }

  if (isSdb702nmSetpointVsAmbientQuery(msg)) {
    blocks.push(
      "",
      "ВНИМАНИЕ — уставка RH ниже влажности помещения (SDB702NM):",
      "Это не отсутствующий параметр и не инструкция SET/UP/DN.",
      "Из контекста: шкаф осушает и не повышает RH выше окружающей; для 0–30 RH% уставка не более RH%окр.ср.−10; от 30 RH% — не более RH%окр.ср.−20.",
      "Если уставка ниже окружающей и допустима (пример 10 RH% при 50 RH% в помещении) — шкаф осушает к уставке: при RH%т > RH%п вентилятор на 60 ± 1 мин (п. 1.1.4.4.1).",
      "Не отвечай «параметр не указан» и не давай инструкцию SET/UP/DN, если спрашивают что будет при 10 % vs 50 % в помещении.",
    );
  }

  if (isSdb702nmFanRestart1RhQuery(msg)) {
    blocks.push(
      "",
      "ВНИМАНИЕ — повторный пуск вентилятора при +1 RH% (SDB702NM):",
      "Это не отсутствующий параметр и не «шаг 0,1 %». По п. 1.1.4.4.1: при RH%т = RH%п вентилятор отключается (режим «Хранения»); повторное включение при RH%т = RH%п + 1 RH%.",
      "Не начинай ответ с «параметр не указан». Шаг 0,1 RH% и точность ±1 RH% — другие строки ТТХ, не этот порог.",
    );
  }

  if (isSdb702nmRhBelowSetpointQuery(msg)) {
    blocks.push(
      "",
      "ВНИМАНИЕ — RH%т ниже порога в режиме «Хранения» (SDB702NM):",
      "Ответ только по п. 1.1.4.4.2: при RH%т ниже RH%п на 1 RH% открываются заслонки осушителя, осушитель отключается от объёма до выравнивания; при RH%т = RH%п заслонки закрываются.",
      "ЗАПРЕЩЕНО: «общие принципы», герметичность/утечки, Wi‑Fi, догадки про датчики без ±1 RH% из ТТХ.",
    );
  }

  if (isSdb702nmLoadHumidityRiseQuery(msg) || isSdb702nmDoorCloseDryDelayQuery(msg)) {
    blocks.push(
      "",
      "ВНИМАНИЕ — дверь / загрузка / задержка осушения SDB702NM:",
      "Не отвечай про «хранение при высокой влажности» и не уходи в состав цеолита, если спрашивают почему влажность выросла или почему не сразу сушит после закрытия двери.",
      "П. 1.1.4.4.1: при открытой двери вентилятор отключается; при закрытии включается, отсчёт ускоренного осушения 60 ± 1 мин начинается заново.",
    );
  }

  if (/открыт[\p{L}]*\s+двер|как\s+открыть\s+двер/i.test(msg)) {
    blocks.push(
      "",
      "ВНИМАНИЕ — открытие дверей SDB702NM:",
      "Двери открываются вручную; отдельной процедуры открытия в РЭ нет.",
      "При открытой двери — звуковой сигнал, красный индикатор, отключение вентилятора осушителя (если есть в контексте).",
    );
  }

  if (isEmergencySmokeQuery(msg)) {
    blocks.push(
      "",
      "ВНИМАНИЕ — ДЫМ / АВАРИЯ SDB702NM (п. 2.4):",
      "Первое действие — немедленно отключить питание шкафа.",
      "Не начинай с проверки герметичности, замков или влажности.",
    );
  }

  if (isRegenerationShutdownQuery(msg)) {
    blocks.push(
      "",
      "ВНИМАНИЕ — выключение при регенерации SDB702NM:",
      "Только запрет из контекста РЭ («ЗАПРЕЩАЕТСЯ выключать… в режиме регенерации»), без выдуманных причин.",
    );
  }

  if (/режим(?:ы|а)?\s+работ|какие\s+режим/i.test(msg)) {
    blocks.push(
      "",
      "ВНИМАНИЕ — режимы SDB702NM:",
      "Список: Хранения, Осушения, Регенерации — с сутью и мощностью из контекста (8 / 20 / 285 Вт — если подтверждено).",
      "Не подставляй 540 Вт и другие значения SDB1106NM.",
    );
  }

  if (/влажност.*не\s+(?:падает|сниж)|не\s+(?:падает|сниж).*влажност/i.test(msg)) {
    blocks.push(
      "",
      "ВНИМАНИЕ — неисправность / влажность SDB702NM:",
      "Приоритет: п. 3.1.4 и табл. 3.2 «Типовые неисправности» из контекста.",
      "Не выдумывай проверки и причины, которых нет в РЭ.",
    );
  }

  if (/wi[\-\s]?fi|mqtt|modbus|интернет|управл[\p{L}]*\s+через\s+интернет/i.test(msg)) {
    blocks.push("", `ВНИМАНИЕ — параметр не в РЭ: ответь «${MODEL_PARAM_NOT_SPECIFIED}».`);
  }

  if (isUnsupportedReplacementQuery(msg)) {
    blocks.push(
      "",
      "ВНИМАНИЕ — замена узла без инструкции в РЭ SDB702NM:",
      "Не выдумывай разборку и не отвечай одной фразой «информация отсутствует».",
      "Сообщи, что в руководстве нет инструкции по замене этого узла, и дай контакты техподдержки SOVTEST ATE: 8 (800) 200-54-17, +7 (4712) 54-54-17, info@sovtest-ate.ru и форму «Техподдержка».",
    );
  }

  if (isSdb702nmGettingStartedQuery(msg)) {
    blocks.push(
      "",
      "ВНИМАНИЕ — первый запуск SDB702NM:",
      "Собери порядок включения из контекста (как правило п. 2.2 / 2.2.5: сеть, розетка, тумблер на кожухе осушителя).",
      "Ethernet, 50 мм от стенок и прочие шаги — только если они есть в контексте и относятся к вопросу. Не начинай ответ с Ethernet, если пользователь спросил, как начать работу.",
    );
  }

  if (isSdb702nmBlinkingRedQuery(msg)) {
    blocks.push(
      "",
      "ВНИМАНИЕ — мигающий красный SDB702NM:",
      "Это штатный режим «Осушения» по п. 1.1.4.3.3 (зелёный + мигающий красный), а не авария и не открытая дверь.",
      "Таблица 3.2 — только если в вопросе есть отказ, коды ошибок или открытая дверь, и это подтверждено контекстом.",
    );
  } else if (isSdb702nmRedLightQuery(msg)) {
    blocks.push(
      "",
      "ВНИМАНИЕ — красная лампочка SDB702NM:",
      "Слово «лампочка» = световой индикатор. Не отвечай, что в контексте нет «лампочки».",
      "По п. 1.1.4.3.3 из контекста: зелёный + мигающий красный — режим «Осушения»; постоянный красный — открыта дверь. Это штатная индикация, не авария «по умолчанию».",
      "Не пиши, что красный сигнал «обычно означает ошибку».",
    );
  }

  if (isSdb702nmWSymbolQuery(msg)) {
    blocks.push(
      "",
      "ВНИМАНИЕ — символ W на LCD SDB702NM:",
      "По контексту это индикация опции подогрева, не код ошибки и не неисправность.",
      "Не уходи в табл. 3.2, если пользователь спрашивает, что значит W.",
    );
  }

  if (isSdb702nmGreenIndicatorQuery(msg)) {
    blocks.push(
      "",
      "ВНИМАНИЕ — зелёный индикатор SDB702NM:",
      "По п. 1.1.4.3.3 зелёный световой сигнал — режим «Хранения», если это есть в контексте. Не отвечай отказом, если зелёный описан в карточке или РЭ.",
    );
  }

  if (isSdb702nmRegenDurationQuery(msg)) {
    blocks.push(
      "",
      "ВНИМАНИЕ — длительность регенерации SDB702NM:",
      "Не подставляй «не более 3 часов» — это выход на влажность с момента включения, не длина цикла регенерации.",
      "Если в контексте нет отдельной длительности регенерации в минутах — скажи, что параметр не указан.",
    );
  }

  if (isSdb702nmNitrogenKitQuery(msg)) {
    blocks.push(
      "",
      "ВНИМАНИЕ — азот в комплекте SDB702NM:",
      "Если азота нет в базовом списке табл. 1.2 — это опция, докупается отдельно. Не ограничивайся перечислением базы без этого вывода.",
    );
  }

  if (isSdb702nmYellowIndicatorQuery(msg)) {
    blocks.push(
      "",
      "ВНИМАНИЕ — жёлтый индикатор SDB702NM:",
      "По п. 1.1.4.3.3 это режим «Регенерации». Запрет выключения — только формулировка из контекста РЭ.",
    );
  }

  if (isSdb702nmAmbientTempQuery(msg)) {
    blocks.push(
      "",
      "ВНИМАНИЕ — температура помещения SDB702NM:",
      "Диапазон эксплуатации помещения из раздела 1.1 (как правило +15…+35 °C), не раздел 5 «Хранение» и не максимум опции подогрева +40 °C.",
      "Не подставляй +5 °C минимума опции подогрева как рабочую температуру цеха.",
      "Не подставляй температуру подогрева, если пользователь спрашивает про цех / окружающий воздух.",
    );
  }

  if (isSdb702nmSetStuckQuery(msg)) {
    blocks.push(
      "",
      "ВНИМАНИЕ — SET не реагирует SDB702NM:",
      "Сначала порядок меню из контекста: SET, затем UP/DN, затем SET. Если индикации совсем нет — проверки питания из табл. 3.2 / п. 3.1.4, без выдуманной разборки.",
    );
  }

  if (isSdb702nmPuddleQuery(msg)) {
    blocks.push(
      "",
      "ВНИМАНИЕ — лужа / «охлаждение» SDB702NM:",
      "В РЭ нет жидкостного контура охлаждения. Не выдумывай утечку охлаждения. Действия — только из контекста (обычно п. 2.4: обесточить, к изготовителю).",
    );
  }

  if (isSdb702nmWheelsQuery(msg)) {
    blocks.push(
      "",
      "ВНИМАНИЕ — ножки и колёса SDB702NM:",
      "Ответ по комплектации из контекста (табл. 1.2): и колёса, и регулируемые ножки. Не утверждай, что чего-то нет, если это есть в таблице.",
    );
  }

  if (isSdb702nmNightOffQuery(msg)) {
    blocks.push(
      "",
      "ВНИМАНИЕ — выключение на ночь SDB702NM:",
      "Различай режимы из контекста: в «Хранении» выключать можно; в «Регенерации» — запрет из РЭ. Не путай с аварийным п. 2.4.",
    );
  }

  if (isSdb702nmHotCaseQuery(msg)) {
    blocks.push(
      "",
      "ВНИМАНИЕ — нагрев корпуса SDB702NM:",
      "+15…+35 °C — температура помещения, не корпуса. Температура опции подогрева (~100 °C / воздух на выходе) — только если опция есть в контексте.",
    );
  }

  if (isSdb702nmTumblerQuery(msg)) {
    blocks.push(
      "",
      "ВНИМАНИЕ — выключатель питания SDB702NM:",
      "«Рубильник» в РЭ — тумблер на кожухе осушителя (п. 2.2.3.1 / 2.2.5), если это есть в контексте. Не подменяй ответ номиналом 220 В.",
    );
  }

  return blocks;
}

function buildSdb702nmDirectSystemPrompt(equipment = null, { manualLoaded = false } = {}) {
  const name = equipment?.name || "SDB702 NM";
  const equipmentLine = equipment
    ? manualLoaded
      ? `Текущий контекст: ${name} (${equipment.id}). Единственный источник фактов — текст руководства ниже; каталог equipment.json игнорируй.`
      : `Текущий контекст оборудования: ${name} (${equipment.id}).`
    : "";

  return [
    ...SDB702NM_EXPERT_ROLE,
    ...SDB702NM_GROUNDING_RULES,
    equipmentLine,
    "Режим: DIRECT_CONTEXT (полный текст РЭ SDB702NM).",
    "Отвечай строго по тексту руководства; указывай номера пунктов и таблиц из РЭ.",
    manualLoaded
      ? "ЗАПРЕЩЕНО использовать данные из каталога оборудования, если их нет в руководстве."
      : "",
  ]
    .filter(Boolean)
    .join("\n");
}

