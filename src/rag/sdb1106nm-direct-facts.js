function extractSection(text, startRe, endRe, maxLen = 12000) {
  const t = String(text || "");
  const m = t.match(startRe);
  if (!m || m.index == null) {
    return "";
  }
  const start = m.index;
  const rest = t.slice(start + m[0].length);
  const endM = rest.match(endRe);
  const body = endM && endM.index != null ? rest.slice(0, endM.index) : rest.slice(0, maxLen);
  return (m[0] + body).trim().slice(0, maxLen);
}

/**
 * Дополнительные выдержки из полного текста РЭ (если PDF загружен).
 */
function extractDynamicSections(docText) {
  const t = String(docText || "");
  if (t.length < 500) {
    return "";
  }

  const parts = [];

  const power = extractSection(
    t,
    /1\.1\.2\.7\s+Потребляемая\s+мощность/i,
    /1\.1\.2\.8\s+Габаритные/i,
    8000
  );
  if (power) {
    parts.push(`[Выдержка: п. 1.1.2.7]\n${power}`);
  }

  const conditions = extractSection(
    t,
    /1\.1\.2\.12\s+Условия\s+эксплуатации/i,
    /1\.1\.2\.13\s+Блок\s+управления/i,
    4000
  );
  if (conditions) {
    parts.push(`[Выдержка: п. 1.1.2.12]\n${conditions}`);
  }

  const prep = extractSection(
    t,
    /2\.2\.4\s+ПОДГОТОВКА\s+К\s+ВКЛЮЧЕНИЮ/i,
    /2\.2\.5\s+ВКЛЮЧЕНИЕ/i,
    6000
  );
  if (prep) {
    parts.push(`[Выдержка: п. 2.2.4–2.2.5]\n${prep}`);
  }

  const inspect = extractSection(
    t,
    /2\.2\.2\s+ВНЕШНИЙ\s+ОСМОТР/i,
    /2\.2\.3\s+ОПИСАНИЕ/i,
    5000
  );
  if (inspect) {
    parts.push(`[Выдержка: п. 2.2.2]\n${inspect}`);
  }

  const modes = extractSection(
    t,
    /1\.1\.4\.4\.1\s+Режим\s+«Осушения»/i,
    /1\.1\.4\.4\.4\s+/i,
    10000
  );
  if (modes) {
    parts.push(`[Выдержка: алгоритм режимов 1.1.4.4]\n${modes}`);
  }

  const table12 = extractTable12Excerpt(t);
  if (table12) {
    parts.push(`[Выдержка: табл. 1.2]\n${table12}`);
  }

  const heating = extractSection(
    t,
    /1\.2\.1\.1\s+Технические\s+характеристики\s+Опция\s+подогрева/i,
    /1\.2\.1\.2\s+Установка\s+параметров/i,
    4000
  );
  if (heating) {
    parts.push(`[Выдержка: п. 1.2.1.1 — подогрев воздуха]\n${heating}`);
  }

  return parts.length ? parts.join("\n\n") : "";
}

/** Табл. 1.2 — комплектность (полки, осушители); всегда включается в direct context. */
