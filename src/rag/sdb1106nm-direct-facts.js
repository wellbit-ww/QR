/**
 * Детерминированные ответы по критическим фактам (без LLM), если вопрос однозначный.
 * @returns {string|null}
 */
/** Выдержки РЭ для safety fast-path (дым → п. 2.4; регенерация → п. 1.1.4.4.3). */
function extractSafetyDocExcerpt(docText, message) {
  const t = String(docText || "");
  if (isEmergencySmokeQuery(message)) {
    const section =
      extractSection(
        t,
        /2\.4\s+[^\n]{0,120}(?:экстремальн|Действия)/iu,
        /2\.5\s+|^\s*3\.\s+/imu,
        6000
      ) ||
      extractSection(t, /2\.4\s+/i, /2\.5\s+/i, 6000);
    return (
      section ||
      "П. 2.4 «Действия в экстремальных условиях»: при дыме, гари или задымлении — немедленно отключить питание шкафа."
    );
  }
  if (isRegenerationShutdownQuery(message)) {
    const section =
      extractSection(t, /1\.1\.4\.4\.3/i, /1\.1\.4\.4\.4/i, 4000) ||
      extractSection(t, /режим\s+«Регенерации»/i, /1\.1\.4\.4\.4/i, 4000);
    return (
      section ||
      "П. 1.1.4.4.3: ЗАПРЕЩАЕТСЯ выключать шкаф в режиме регенерации осушителя."
    );
  }
  return t.slice(0, 12000);
}

