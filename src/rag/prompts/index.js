function asksOperatingConditionsNumericCompare(msg) {
  const m = String(msg || "");
  if (!/\d/.test(m)) {
    return false;
  }
  return /условия\s+эксплуатации|1\.1\.3|эксплуатац|допустим|входит\s+ли|соответствует|нарушен|максимальн|минимальн|можно\s+ли|при\s+температур|при\s+влажност|кпа|°\s*[сc]|%rh|\d+\s*(?:в\b|гц|кпа)/iu.test(
    m
  );
}

function equipmentHeader(equipment) {
  if (!equipment) {
    return "Оборудование не указано.";
  }
  return [
    `Текущий контекст оборудования: ${equipment.name} (${equipment.id}).`,
    equipment.description ? `Описание: ${equipment.description}.` : "",
    equipment.summary ? `Известные факты: ${equipment.summary}` : "",
  ]
    .filter(Boolean)
    .join("\n");
}

/**
 * Динамические подсказки перед генерацией ответа (смешанные таблицы, режим хранения, полки).
 */
function buildLlmAnswerCompositionBlocks(retrievalContext, userMessage = "", equipment = null) {
  const blocks = [];
  const ctx = String(retrievalContext || "");
  const msg = String(userMessage || "");

  if (shouldApplySdb1106nmModelContextFilter(msg, ctx, equipment)) {
    blocks.push("", ...modelContextFilterPromptLines());
  }

  if (isEmergencySmokeQuery(msg)) {
    blocks.push(
      "",
      "ВНИМАНИЕ — ДЫМ / АВАРИЯ (п. 2.4, приоритет №1):",
      "Первое и главное действие — НЕМЕДЛЕННО отключить питание шкафа.",
      "ЗАПРЕЩЕНО начинать ответ с проверки герметичности, замков, влажности или внешнего осмотра.",
      "Регенерация и осушение не отменяют немедленное отключение при дыме.",
    );
  }

  if (contextHasCompetingSdbModels(ctx)) {
    blocks.push(
      "",
      "ВНИМАНИЕ — в контексте таблица с несколькими моделями:",
      `Только ${SDB1106NM_PRODUCT_MODEL}; чужие артикулы в ответе запрещены. Формат — полное предложение с цифрой.`,
      "Пример: «Масса шкафа SDB1106NM в базовой комплектации составляет 180 кг.»",
    );
  }

  if (asksOperatingConditionsNumericCompare(msg)) {
    blocks.push(
      "",
      "ВНИМАНИЕ — сравнение числа с условиями эксплуатации (п. 1.1.3):",
      "Сопоставь значение из вопроса с диапазоном из контекста; вне диапазона — явное «нарушение»/«не соответствует».",
      "Не используй abstain, если диапазон есть в контексте.",
    );
  }

  if (asksHeatingTemperatureSetup(msg)) {
    blocks.push(
      "",
      "ВНИМАНИЕ — опция «Система подогрева» (п. 2.3.3.1):",
      "Ответ — только температура нагрева (°C), диапазон +20…+40 °C; выше +40 °C (напр. +50 °C) — запрещено.",
      "Не подменяй ответ мощностью (Вт) из таблицы ТТХ, если вопрос только про установку температуры.",
    );
  }

  const normalIndicator = resolveNormalIndicatorMode(msg);
  if (normalIndicator) {
    blocks.push(
      "",
      "ВНИМАНИЕ — световые индикаторы (п. 1.1.4.3.3), штатный режим:",
      `${normalIndicator.labelRu}.`,
      "Это НЕ неисправность; не направляй в «Перечень возможных неисправностей» без признаков поломки.",
      "Жёлтый — регенерация (норма); зелёный + мигающий красный — осушение (норма); зелёный без мигания — хранение.",
    );
  }

  if (asksOperatingModesOverview(msg)) {
    blocks.push(
      "",
      "ВНИМАНИЕ — обзор режимов работы (п. 2.2):",
      "Маркированный список; к каждому режиму — суть + цифры из контекста (мощность, температура, время).",
      "• Хранение: поддержание влажности, минимальное потребление (напр. ≤8 Вт).",
      "• Осушение: активное снижение влажности до порога.",
      "• Регенерация: восстановление осушителя при нагреве (напр. 540 Вт — если в контексте).",
    );
  } else if (asksStorageModePower(msg) && contextSupportsStorageMode8W(ctx)) {
    blocks.push(
      "",
      "ВНИМАНИЕ — мощность в режиме хранения (п. 2.2.7.1):",
      "Одно-два предложения «тезис + факт», например про предел 8 Вт; без обзора всех режимов.",
    );
  }

  if (asksNitrogenConcentration(msg) && !asksHowToConfigure(msg)) {
    blocks.push(
      "",
      "ВНИМАНИЕ — диапазон азота:",
      "Одно полное предложение с процентами; без меню и таймеров.",
    );
  }

  if (asksShelfLoadCapacity(msg)) {
    blocks.push(
      "",
      "ВНИМАНИЕ — нагрузка на полку:",
      "Несколько типов — буллеты «тип полки: суть + кг»; один тип — 1–2 предложения; без чужих моделей.",
    );
  }

  if (asksHowToConfigure(msg)) {
    blocks.push("", "ВНИМАНИЕ — запрошена настройка: допустим пошаговый формат из контекста.");
  }

  if (isHumidityNotDroppingQuery(msg)) {
    blocks.push(
      "",
      "ВНИМАНИЕ — влажность не падает / не выходит на режим (TROUBLESHOOTING):",
      "Приоритет: перечень возможных неисправностей (п. 2.2.2, табл. 3.2), не только общие режимы.",
      "В блоке «Что проверить» ОБЯЗАТЕЛЬНО включи все три пункта из РЭ:",
      ...HUMIDITY_MANDATORY_CHECKS.map((line, i) => `${i + 1}. ${line}`),
    );
  }

  if (/дым|гарь|регенерац|выключ.*при|при.*регенерац|2\.4\b|аварийн/i.test(msg)) {
    blocks.push(
      "",
      "ВНИМАНИЕ — SAFETY:",
      "Только формулировки из контекста; без «риск пожара», «может привести», «из-за риска».",
      "Дым/гари — немедленное отключение питания по п. 2.4; регенерация не отменяет это.",
      "Запрет выключения при регенерации — только п. 1.1.4.4.3, без п. 2.4.",
    );
  }

  return blocks.length ? blocks.join("\n") : "";
}

