function tryDeterministicSdb302nmAnswer(message, options = {}) {
  const text = String(message || "").trim();
  const history = options.history || [];
  if (!text) {
    return null;
  }
  if (isUnsupportedSdb302nmSpecQuery(text)) {
    return buildUnsupportedSdb302nmSpecReply();
  }
  if (isContactSupportQuery(text)) {
    return buildPortalContactSupportAnswer();
  }
  if (isUnsupportedReplacementQuery(text, history)) {
    return buildUnsupportedReplacementAnswer("SDB302NM", text, history);
  }
  if (isEquipmentSerialNumberQuery(text)) {
    return resolveSerialNumberAnswer(text, "SDB302NM");
  }
  if (isEmergencySmokeQuery(text)) {
    return "При появлении **дыма**, запаха **гари** или других признаков аварии SDB302NM (п. **2.4**): **немедленно отключите питание** (вилку из розетки или тумблер «ВЫКЛ»). Не проверяйте уплотнители, замки или RH до обесточивания.";
  }
  if (isSdb302nmWSymbolQuery(text)) {
    return ANSWER_W_SYMBOL;
  }
  if (isSdb302nmGreenStorageQuery(text)) {
    return ANSWER_GREEN_STORAGE;
  }
  if (isSdb302nmHotCaseQuery(text)) {
    return ANSWER_HOT_CASE;
  }
  if (isSdb302nmShopAmbientQuery(text)) {
    return ANSWER_SHOP_AMBIENT;
  }
  if (isSdb302nmWheelsQuery(text)) {
    return ANSWER_WHEELS_KIT;
  }
  if (isSdb302nmLoadHumidityRiseQuery(text)) {
    return ANSWER_LOAD_HUMIDITY_RISE;
  }
  if (isSdb302nmDoorCloseDryDelayQuery(text)) {
    return ANSWER_DOOR_CLOSE_DRY_DELAY;
  }
  if (isSdb302nmSetpointVsAmbientQuery(text)) {
    return ANSWER_SETPOINT_VS_AMBIENT;
  }
  if (isSdb302nmFanRestart1RhQuery(text)) {
    return ANSWER_FAN_RESTART_1RH;
  }
  if (isSdb302nmRhBelowSetpointQuery(text)) {
    return ANSWER_RH_BELOW_SETPOINT;
  }
  if (/диэлектрик/iu.test(text)) {
    const dielectric = pickFact((fact) => /Да\. По п\./u.test(fact.answer) && /диэлектриков/u.test(fact.answer));
    if (dielectric) {
      return dielectric;
    }
  }
  if (
    /влажност/iu.test(text) &&
    /(?:высок|повышен|больш)[\p{L}]*\s+влажност/iu.test(text) &&
    !/(?:диапазон|шаг|точност|порог|меню|\bSET\b|не\s+падает|не\s+сниж|почему|загруз|опуст|ниже\s+установлен)/iu.test(text)
  ) {
    const highHumidity = pickFact((fact) => /нужна высокая влажность/u.test(fact.answer));
    if (highHumidity) {
      return highHumidity;
    }
  }
  if (/(?:(?:выключ|отключ).{0,40}регенерац|регенерац.{0,40}(?:выключ|отключ))/iu.test(text)) {
    return pickFact((fact) => /Запрещается выключать/u.test(fact.answer));
  }
  if (/(?:давлен[\p{L}]*\s+азот|азот[\p{L}]*\s+давлен|сколько\s+бар|бар\s+максимум)/iu.test(text)) {
    return pickFact((fact) => /6 бар/u.test(fact.answer));
  }
  if (
    /(?:как\s+(?:задать|установ|настро|измен|выстав).*влажност|измен.*(?:значен[\p{L}]*\s+)?влажност|порог.*влажност|меню.*влажност)/iu.test(
      text,
    ) &&
    !/точн|через\s+как[\p{L}]*\s+время|выйти\s+на|выход[\p{L}]*\s+на\s+(?:установленн[\p{L}]*\s+)?режим/iu.test(text)
  ) {
    return pickFact((fact) => /\*\*SET\*\*/u.test(fact.answer) && /\*\*UP\/DN\*\*/u.test(fact.answer));
  }
  if (/(?:как\s+контрол[\p{L}]*.*влажност|контрол[\p{L}]*.*влажност.*(?:внутри|шкаф))/iu.test(text)) {
    return pickFact((fact) => /датчиком RH/u.test(fact.answer));
  }
  if (/(?:защищ[\p{L}]*.*(?:от\s+)?влаг|каким\s+образом.*влаг)/iu.test(text)) {
    return pickFact((fact) => /цеолит/u.test(fact.answer) && /защищ/u.test(fact.answer));
  }
  if (/(?:как\s+часто.*(?:обслужив|меня|замен)|осушител[\p{L}]*\s+когда\s+меня|блок\s+осушен|какие\s+операц[\p{L}]*\s+.*обслужив|периодич.*осуш)/iu.test(text)) {
    return pickFact((fact) => /36 месяцев/u.test(fact.answer) && /регламенту ТО/u.test(fact.answer));
  }
  if (/(?:после\s+длительн[\p{L}]*\s+хранен|действи[\p{L}]*\s+.*после.*длительн[\p{L}]*\s+хранен)/iu.test(text)) {
    return pickFact((fact) => /не указано/u.test(fact.answer) && /длительн/u.test(fact.answer));
  }
  if (/(?:что\s+.*провер.*перед\s+(?:начал[\p{L}]*\s+)?эксплуатац|перед\s+начал[\p{L}]*\s+эксплуатац)/iu.test(text)) {
    return pickFact((fact) => /комплектност/u.test(fact.answer) && /эксплуатац/iu.test(fact.answer));
  }
  if (/(?:какие\s+узл[\p{L}]*\s+.*(?:периодич|провер)|узл[\p{L}]*\s+.*периодич[\p{L}]*\s+провер)/iu.test(text)) {
    return pickFact((fact) => /блок осушения/u.test(fact.answer) && /Периодически проверяют/u.test(fact.answer));
  }
  if (/(?:влажност.*не\s+(?:падает|сниж)|не\s+(?:падает|сниж).*влажност)/iu.test(text)) {
    return pickFact((fact) => /отсутствии снижения влажности/u.test(fact.answer));
  }
  if (/(?:производител.*датчик|бренд.*датчик|датчик.*(?:siemens|honeywell|производител|бренд))/iu.test(text)) {
    return pickFact((fact) => /не указан/u.test(fact.answer));
  }
  if (/(?:ротаметр|рпост|ррег)/iu.test(text)) {
    return pickFact((fact) => /Рпост/u.test(fact.answer));
  }
  if (/(?:ограничен.*загруз|загруз.*полк|размещен.*полк)/iu.test(text)) {
    return pickFact((fact) => /50 мм/u.test(fact.answer) && /загрузке/u.test(fact.answer));
  }
  if (/(?:азот.*двер|двер.*азот|азот.*таймер)/iu.test(text)) {
    return pickFact((fact) => /Ррег/u.test(fact.answer) && /таймер/u.test(fact.answer));
  }
  if (/(?:что\s+означает\s+режим\s+осуш|что\s+такое\s+режим\s+осуш)/iu.test(text)) {
    return FACTS.find((fact) => /мигающий красный/u.test(fact.answer))?.answer || null;
  }
  if (/(?:что\s+за\s+красн|красн[\p{L}]*\s+(?:ламп|огон|светодиод)|(?:ламп|лампочк|огон[её]к)[\p{L}]*\s+красн)/iu.test(text) && !/двер/iu.test(text)) {
    return pickFact((fact) => /постоянный красный/u.test(fact.answer) && /Осушения/u.test(fact.answer));
  }
  if (/(?:кто\s+.*(?:производител|изготовител).*шкаф|производител.*шкаф)/iu.test(text)) {
    return FACTS.find((fact) => /Совтест/u.test(fact.answer))?.answer || null;
  }
  if (/(?:групп[\p{L}]*.*электробезопас.*оператор|оператор.*групп[\p{L}]*.*электробезопас)/iu.test(text)) {
    return FACTS.find((fact) => /не ниже I/u.test(fact.answer) && /оператор/iu.test(fact.answer))?.answer || null;
  }
  const match = FACTS.find((fact) => !fact.skip?.(text) && fact.test.test(text));
  return match ? match.answer : null;
}

function buildSdb302nmDirectSystemContent(systemPrompt, docText) {
  return `${systemPrompt}\n\n${SDB302NM_CRITICAL_FACTS}\n\nПолный текст руководства (единственный источник для процедур, обслуживания и безопасности):\n\n${docText}`;
}

function extractSafetyDocExcerpt(docText, message) {
  const text = String(docText || "").trim();
  if (!text) {
    return "";
  }
  const headings = [
    text.toUpperCase().lastIndexOf("ДЕЙСТВИЯ В ЭКСТРЕМАЛЬНЫХ УСЛОВИЯХ"),
    text.toUpperCase().lastIndexOf("МЕРЫ БЕЗОПАСНОСТИ"),
    text.toUpperCase().lastIndexOf("ЗАПРЕЩАЕТСЯ"),
  ].filter((index) => index >= 0);
  const start = headings.length ? Math.min(...headings) : 0;
  void message;
  return text.slice(start, start + 12000);
}

function buildSafetyDeterministicOrPrompt(message, docText) {
  const answer = tryDeterministicSdb302nmAnswer(message);
  return answer
    ? { mode: "deterministic", answer }
    : { mode: "grounded_llm", sectionHints: ["section_2_2_1", "section_2_4"], docExcerpt: extractSafetyDocExcerpt(docText, message) };
}

