function isSdb302nmShopAmbientQuery(text) {
  if (/подогрев|корпус|обожг|ожог/iu.test(text)) {
    return false;
  }
  return /(?:цех|помещен).{0,80}(?:12|\+\s*12)|(?:12|\+\s*12).{0,80}(?:цех|помещен|диапазон|включа)|градус[\p{L}]*\s*12|12\s*градус/iu.test(
    text,
  );
}

function isSdb302nmGreenStorageQuery(text) {
  return isSdb302nmGreenIndicatorQuery(text) && !/красн|мига|осушен/iu.test(text);
}

